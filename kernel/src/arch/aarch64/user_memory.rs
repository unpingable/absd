use super::*;
pub(super) unsafe fn translated(
    space: &AddressSpace,
    address: u64,
    writable: bool,
) -> Result<u64, UserMemoryError> {
    if address >= USER_ADDRESS_LIMIT {
        return Err(UserMemoryError::SupervisorAddress);
    }
    let mut table = space.root;
    for (level, shift) in [39, 30, 21, 12].into_iter().enumerate() {
        let entry = unsafe {
            core::ptr::read_volatile((table as *const u64).add(((address >> shift) & 511) as usize))
        };
        if entry & 3 != 3 {
            return Err(UserMemoryError::Unmapped);
        }
        if level == 3 {
            if entry & (1 << 6) == 0 {
                return Err(UserMemoryError::Unmapped);
            }
            #[cfg(not(absd_mutant_ignore_writable))]
            if writable && entry & (1 << 7) != 0 {
                return Err(UserMemoryError::NotWritable);
            }
            #[cfg(absd_mutant_ignore_writable)]
            let _ = writable;
            return Ok((entry & 0x0000_ffff_ffff_f000) + (address & 4095));
        }
        // Table AP/XN restrictions are never generated by this port.
        if entry & ((3 << 61) | (1 << 60)) != 0 {
            return Err(UserMemoryError::Unmapped);
        }
        table = entry & 0x0000_ffff_ffff_f000;
    }
    Err(UserMemoryError::Unmapped)
}

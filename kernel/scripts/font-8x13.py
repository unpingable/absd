#!/usr/bin/env python3
"""Regenerates fbcon/src/font8x13.rs from the X11 misc-fixed 8x13 font.

Source: font-misc-misc `8x13-ISO8859-1.pcf.gz` (Debian package xfonts-base),
whose COPYING reads "Public domain font.  Share and enjoy."  Only printable
ASCII (0x20..0x7e) is kept, one byte per 8-pixel row, most significant bit
leftmost, 13 rows per glyph aligned to the font's ascent.

    python3 scripts/font-8x13.py [PCF_GZ] > fbcon/src/font8x13.rs
"""

import gzip
import struct
import sys

PCF_METRICS, PCF_BITMAPS, PCF_BDF_ENCODINGS, PCF_ACCELERATORS = 1 << 2, 1 << 3, 1 << 5, 1 << 1
WIDTH, HEIGHT = 8, 13


def tables(data):
    assert data[:4] == b"\x01fcp", "not a PCF file"
    (count,) = struct.unpack_from("<I", data, 4)
    found = {}
    for index in range(count):
        kind, fmt, size, offset = struct.unpack_from("<IIII", data, 8 + 16 * index)
        found[kind] = (fmt, offset)
    return found


def order(fmt):
    return ">" if fmt & 4 else "<"


def metrics(data, fmt, offset):
    (fmt,) = struct.unpack_from("<I", data, offset)
    e = order(fmt)
    if fmt & 0x100:
        (count,) = struct.unpack_from(e + "H", data, offset + 4)
        rows = []
        for i in range(count):
            lb, rb, w, a, d = struct.unpack_from("5B", data, offset + 6 + 5 * i)
            rows.append((lb - 0x80, rb - 0x80, w - 0x80, a - 0x80, d - 0x80))
        return rows
    (count,) = struct.unpack_from(e + "I", data, offset + 4)
    return [struct.unpack_from(e + "5hH", data, offset + 8 + 12 * i)[:5] for i in range(count)]


def bitmaps(data, offset):
    (fmt,) = struct.unpack_from("<I", data, offset)
    e = order(fmt)
    (count,) = struct.unpack_from(e + "I", data, offset + 4)
    offsets = struct.unpack_from(e + f"{count}I", data, offset + 8)
    sizes = struct.unpack_from(e + "4I", data, offset + 8 + 4 * count)
    pad = 1 << (fmt & 3)
    start = offset + 8 + 4 * count + 16
    blob = data[start:start + sizes[fmt & 3]]
    assert fmt & 8, "expected most-significant-bit-first bitmaps"
    return offsets, blob, pad


def encodings(data, offset):
    (fmt,) = struct.unpack_from("<I", data, offset)
    e = order(fmt)
    min2, max2, min1, max1, default = struct.unpack_from(e + "5H", data, offset + 4)
    columns = max2 - min2 + 1
    rows = max1 - min1 + 1
    table = struct.unpack_from(e + f"{columns * rows}H", data, offset + 14)
    def glyph(code):
        if min1 != 0 or not (min2 <= code <= max2):
            return None
        value = table[code - min2]
        return None if value == 0xFFFF else value
    return glyph


def accelerators(data, offset):
    (fmt,) = struct.unpack_from("<I", data, offset)
    e = order(fmt)
    ascent, descent = struct.unpack_from(e + "ii", data, offset + 4 + 8)
    return ascent, descent


def glyphs(path="/usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz"):
    """{code: [13 row bytes]} for printable ASCII, straight from the PCF."""
    data = gzip.open(path).read()
    found = tables(data)
    glyph_metrics = metrics(data, None, found[PCF_METRICS][1])
    offsets, blob, pad = bitmaps(data, found[PCF_BITMAPS][1])
    lookup = encodings(data, found[PCF_BDF_ENCODINGS][1])
    ascent, descent = accelerators(data, found[PCF_ACCELERATORS][1])
    assert ascent + descent == HEIGHT, (ascent, descent)
    out = {}
    for code in range(0x20, 0x7F):
        index = lookup(code)
        assert index is not None, f"missing glyph {code:#x}"
        lb, rb, width, g_ascent, g_descent = glyph_metrics[index]
        assert width == WIDTH and lb >= 0 and rb <= WIDTH, (code, glyph_metrics[index])
        stride = ((rb - lb + 7) // 8 + pad - 1) // pad * pad
        rows = [0] * HEIGHT
        for row in range(g_ascent + g_descent):
            target = ascent - g_ascent + row
            byte = blob[offsets[index] + row * stride]
            rows[target] = byte >> lb
        out[code] = rows
    return out


def main():
    table = glyphs(*sys.argv[1:2])
    out = [table[code] for code in range(0x20, 0x7F)]
    print("//! Printable ASCII (0x20..=0x7e) from the X11 misc-fixed 8x13 font.")
    print("//!")
    print("//! Source: font-misc-misc `8x13-ISO8859-1` (\"Public domain font.  Share and")
    print("//! enjoy.\"). Generated by `scripts/font-8x13.py`; do not edit by hand.")
    print("//! One byte per row, most significant bit leftmost.")
    print()
    print(f"pub const GLYPH_WIDTH: usize = {WIDTH};")
    print(f"pub const GLYPH_HEIGHT: usize = {HEIGHT};")
    print("pub const FIRST: u8 = 0x20;")
    print("pub const LAST: u8 = 0x7e;")
    print()
    print(f"pub const GLYPHS: [[u8; GLYPH_HEIGHT]; {len(out)}] = [")
    for code, rows in zip(range(0x20, 0x7F), out):
        body = ", ".join(f"0x{r:02x}" for r in rows)
        label = chr(code) if code != 0x5C else "backslash"
        print(f"    [{body}], // {label!r}" if code != 0x20 else f"    [{body}], // space")
    print("];")


if __name__ == "__main__":
    main()

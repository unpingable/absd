#!/usr/bin/env python3
"""Finite capture substitutions; these are not QUIC engine or native runs."""
import importlib.util
import ipaddress
from pathlib import Path
import struct
import unittest
from unittest import mock

spec = importlib.util.spec_from_file_location("quic6_wire", Path(__file__).with_name("native-quic-ipv6-wire.py"))
wire = importlib.util.module_from_spec(spec)
spec.loader.exec_module(wire)
GM, PM = "52:54:00:ab:5d:15", "52:55:00:00:02:02"
G, P = (ipaddress.IPv6Address(text).packed for text in ("fd00:ab5d::15", "fd00:ab5d::2"))
NS = bytes.fromhex("3333ff000002525400ab5d1586dd6000000000203afffd00ab5d000000000000000000000015ff0200000000000000000001ff000002870078b400000000fd00ab5d0000000000000000000000020101525400ab5d15")
NA = bytes.fromhex("525400ab5d1552550000020286dd6000000000203afffd00ab5d000000000000000000000002fd00ab5d0000000000000000000000158800c81760000000fd00ab5d0000000000000000000000020201525500000202")
PEER = bytes.fromhex("525400ab5d1552550000020286dd6000000000141140fd00ab5d000000000000000000000002fd00ab5d000000000000000000000015115b1e78001431f9717569632d776972652d7636")
Q01 = dict(id="Q01", peer_mode="echo", local_port=7800)
Q08 = dict(id="Q08", peer_mode="wrong-root", local_port=7807)
Q17 = dict(id="Q17", peer_mode="denied-destination", local_port=7816)


def check(data):
    # Independent test-side checksum; literal ND and peer vectors above are
    # also checked by the pinned existing classifier, never generated by it.
    data += bytes(len(data) % 2)
    total = sum(int.from_bytes(data[i:i + 2], "big") for i in range(0, len(data), 2))
    while total >> 16:
        total = (total & 65535) + (total >> 16)
    return (~total) & 65535


def packet(outgoing=True, port=7800, size=1200, source=None, destination=None,
           source_mac=None, destination_mac=None, hop=64, ecn=0, version=1, first_byte=0xc0):
    src, dst = (G, P) if outgoing else (P, G)
    sm, dm = (GM, PM) if outgoing else (PM, GM)
    src, dst = source or src, destination or dst
    sm, dm = source_mac or sm, destination_mac or dm
    sport, dport = (port, 4443) if outgoing else (4443, port)
    body = (bytes([first_byte]) + version.to_bytes(4, "big") + bytes(max(0, size - 5)))[:size]
    segment = struct.pack("!HHHH", sport, dport, len(body) + 8, 0) + body
    value = check(src + dst + struct.pack("!I3xB", len(segment), 17) + segment)
    segment = segment[:6] + (value or 65535).to_bytes(2, "big") + segment[8:]
    return (bytes.fromhex(dm.replace(":", "")) + bytes.fromhex(sm.replace(":", "")) + b"\x86\xdd" +
            bytes([0x60, ecn << 4, 0, 0]) + struct.pack("!HBB", len(segment), 17, hop) + src + dst + segment)


def mld():
    src, dst = (ipaddress.IPv6Address(s).packed for s in ("fe80::2", "ff02::16"))
    body = b"\x8f\0" + bytes(6)
    value = check(src + dst + struct.pack("!I3xB", len(body), 58) + body)
    body = body[:2] + value.to_bytes(2, "big") + body[4:]
    hbh = b"\x3a\0\x05\x02\0\0\x01\0"
    return (bytes.fromhex("33330000001652550000020286dd60000000") +
            struct.pack("!HBB", len(hbh) + len(body), 0, 1) + src + dst + hbh + body)


def pcap(frames):
    raw = struct.pack("<IHHIIII", 0xa1b2c3d4, 2, 4, 0, 0, 65536, 1)
    for i, frame in enumerate(frames):
        raw += struct.pack("<IIII", 1, i, len(frame), len(frame)) + frame
    return raw


class IPv6WireControls(unittest.TestCase):
    def observed(self, frames=None, case=None):
        return wire.observe(pcap(frames if frames is not None else [NS, NA, packet(), PEER]), case or Q01, GM, PM)

    def test_literal_nd_and_exact_udp_positive_calibrate(self):
        result = self.observed()
        self.assertEqual(result["frame_count"], 4)
        self.assertEqual(result["guest_udp_count"], 1)
        self.assertEqual(result["peer_udp_count"], 1)
        self.assertEqual(result["guest_udp_bytes"], 1200)
        self.assertEqual(result["peer_udp"][0]["bytes"], 12)
        self.assertEqual(result["unexpected_frames"], 0)

    def test_wrong_root_uses_its_exact_canonical_port(self):
        self.observed([NS, NA, packet(port=7807), packet(False, port=7807)], Q08)
        with self.assertRaises(wire.Refusal): self.observed(case=Q08)

    def test_denied_profile_accepts_no_protocol_frames(self):
        result = self.observed([], Q17)
        self.assertEqual(result["frame_count"], 0)
        for frame in (NS, NA, packet(port=7816)):
            with self.assertRaises(wire.Refusal): self.observed([frame], Q17)

    def test_valid_linux_mld_remains_in_complete_census(self):
        result = self.observed([mld(), NS, NA, packet(), PEER])
        self.assertEqual(result["frame_count"], 5)
        self.assertEqual(len(result["linux_mldv2"]), 1)
        self.assertTrue(result["linux_mldv2"][0]["filter_refused"])
        self.assertEqual(self.observed([mld()], Q17)["frame_count"], 1)

    def test_unknown_case_mode_and_port_refuse(self):
        for case in (dict(Q01, id="Q03"), dict(Q01, local_port=7801), dict(Q01, peer_mode="other")):
            with self.assertRaises(wire.Refusal): self.observed(case=case)

    def test_missing_nd_or_wrong_order_refuses(self):
        for frames in ([packet(), PEER], [NA, NS, packet(), PEER], [NS, packet(), NA, PEER]):
            with self.assertRaises(wire.Refusal): self.observed(frames)

    def test_third_mac_or_wrong_tuple_refuses(self):
        for changed in (packet(source_mac="52:54:00:ab:5d:16"), packet(port=7801),
                        packet(source=ipaddress.IPv6Address("fd00:ab5d::16").packed),
                        packet(destination=ipaddress.IPv6Address("fd00:ab5d::3").packed),
                        packet(destination_mac=GM)):
            with self.assertRaises(wire.Refusal): self.observed([NS, NA, changed, PEER])

    def test_mtu_1200_and_1201_boundary(self):
        self.observed()
        for changed in (packet(size=1201), packet(False, size=1201)):
            with self.assertRaises(wire.Refusal): self.observed([NS, NA, packet(), changed, PEER])

    def test_native_ecn_and_hop_mismatch_refuse(self):
        for changed in (packet(ecn=1), packet(ecn=2), packet(hop=63), packet(False, hop=63)):
            with self.assertRaises(wire.Refusal): self.observed([NS, NA, packet(), changed, PEER])

    def test_invalid_udp_or_nd_checksum_refuses(self):
        for ordinal in range(4):
            frames = [NS, NA, packet(), PEER]
            changed = bytearray(frames[ordinal]); changed[-1] ^= 1; frames[ordinal] = bytes(changed)
            with self.assertRaises(wire.Refusal): self.observed(frames)

    def test_unknown_ethertype_or_ipv4_refuses(self):
        for ether in (b"\x08\0", b"\x08\x06", b"\x81\0"):
            changed = packet()[:12] + ether + packet()[14:]
            with self.assertRaises(wire.Refusal): self.observed([NS, NA, changed, PEER])

    def test_short_initial_shape_and_missing_direction_refuse(self):
        for frames in ([NS, NA, packet(size=1199), PEER], [NS, NA, packet()], [NS, NA, PEER]):
            with self.assertRaises(wire.Refusal): self.observed(frames)

    def test_no_original_profile_mutation(self):
        original = wire.accounting()
        before = repr(original.PROFILES)
        with mock.patch.object(wire, "accounting", return_value=original):
            self.observed()
        self.assertEqual(repr(original.PROFILES), before)
        self.assertEqual(set(original.PROFILES), {"udp", "tcp"})

    def test_partial_truncated_and_invalid_capture_records_refuse(self):
        raw = pcap([NS, NA, packet(), PEER])
        for changed in (raw[:-1], raw + b"x", raw + bytes(16)):
            with self.assertRaises(wire.Refusal): wire.observe(changed, Q01, GM, PM)

    def test_invalid_capture_header_or_mac_refuses(self):
        raw = pcap([NS, NA, packet(), PEER])
        for changed in (bytes(24), raw[:20] + (2).to_bytes(4, "little") + raw[24:]):
            with self.assertRaises(wire.Refusal): wire.observe(changed, Q01, GM, PM)
        for gm, pm in ((GM, GM), ("00:00:00:00:00:00", PM), ("53:54:00:ab:5d:15", PM), (GM.upper(), PM)):
            with self.assertRaises(wire.Refusal): wire.observe(raw, Q01, gm, pm)

    def test_zero_udp_checksum_fragment_and_extension_headers_refuse(self):
        zero = bytearray(packet()); zero[60:62] = bytes(2)
        for changed in (bytes(zero), packet()[:20] + b"\x2c" + packet()[21:],
                        packet()[:20] + b"\0" + packet()[21:]):
            with self.assertRaises(wire.Refusal): self.observed([NS, NA, changed, PEER])

    def test_checksum_valid_wrong_nd_target_refuses(self):
        changed = bytearray(NA); changed[77] ^= 1; changed[56:58] = bytes(2)
        value = check(bytes(changed[22:54]) + struct.pack("!I3xB", len(changed) - 54, 58) + bytes(changed[54:]))
        changed[56:58] = value.to_bytes(2, "big")
        with self.assertRaises(wire.Refusal): self.observed([NS, bytes(changed), packet(), PEER])

    def test_full_capture_count_and_source_pin_boundaries_refuse(self):
        with self.assertRaises(wire.Refusal): self.observed([NS, NA, packet()] + [PEER] * 254)
        with mock.patch.object(wire, "ACCOUNTING_SHA256", "0" * 64), self.assertRaises(wire.Refusal):
            self.observed()

    def test_first_initial_requires_cleartext_version1_and_initial_type(self):
        self.assertEqual(self.observed()["guest_udp"][0]["long_header_version"], 1)
        for version in (0, 2, 0xffffffff):
            with self.subTest(version=version), self.assertRaises(wire.Refusal):
                self.observed([NS, NA, packet(version=version), PEER])
        for first_byte in (0x40, 0x80, 0xd0, 0xe0, 0xf0):
            with self.subTest(first_byte=first_byte), self.assertRaises(wire.Refusal):
                self.observed([NS, NA, packet(first_byte=first_byte), PEER])


if __name__ == "__main__":
    unittest.main()

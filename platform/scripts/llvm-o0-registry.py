#!/usr/bin/env python3
"""Write the pass registry of the -O0-only LLVM image (scripts/build-llvm-kit.sh).

Reads llvm/lib/Passes/PassRegistry.def and writes PassRegistryO0.def beside it:
the same file with every pass entry (MODULE_PASS, CGSCC_PASS, FUNCTION_PASS,
LOOPNEST_PASS, LOOP_PASS and their _WITH_PARAMS forms) removed and every
analysis entry, macro default and #undef kept. PassBuilder.cpp includes it
under LLVM_ABSD_O0_ONLY (cxx/patches/llvm/0009), so textual pass pipelines
(-passes=, -mllvm -print-*) name no pass in that image, and no optimization
pass is reachable from the registry. Analyses stay: the -O0 pipeline and
the code generator ask for them by type.
Usage: llvm-o0-registry.py PassRegistry.def PassRegistryO0.def
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
PASS = re.compile(r'^(MODULE|CGSCC|FUNCTION|LOOPNEST|LOOP)_PASS(_WITH_PARAMS)?\(')
out, kept, dropped = [], 0, 0
lines = open(src).read().split('\n')
i = 0
while i < len(lines):
    line = lines[i]
    if PASS.match(line):
        depth = 0
        while True:
            depth += lines[i].count('(') - lines[i].count(')')
            i += 1
            if depth <= 0:
                break
        dropped += 1
        continue
    if re.match(r'^[A-Z_]+_ANALYSIS\(', line):
        kept += 1
    out.append(line)
    i += 1
header = ('// Generated by scripts/llvm-o0-registry.py from PassRegistry.def: pass\n'
          f'// entries removed ({dropped}), analysis entries kept ({kept}).\n')
open(dst, 'w').write(header + '\n'.join(out))
print(f"LLVM O0 REGISTRY passes-dropped={dropped} analyses-kept={kept}")
